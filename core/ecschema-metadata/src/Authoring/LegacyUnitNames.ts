const foldName = (name: string): string => name.toUpperCase();
const foldECName = (name: string): string => name.replace(/[.:]/g, ":").toUpperCase();

let foldedOldToNewName: Map<string, string> | undefined;
let foldedNewNameToECName: Map<string, string> | undefined;
let foldedECNameToNewName: Map<string, string> | undefined;
let foldedNewNameToLegacyName: Map<string, string> | undefined;

function getFoldedOldToNewName(): ReadonlyMap<string, string> {
  if (foldedOldToNewName === undefined) {
    foldedOldToNewName = new Map();
    for (const [oldName, newName] of oldToNewName)
      foldedOldToNewName.set(foldName(oldName), newName);
  }
  return foldedOldToNewName;
}

function getFoldedNewNameToECName(): ReadonlyMap<string, string> {
  if (foldedNewNameToECName === undefined) {
    foldedNewNameToECName = new Map();
    for (const [newName, ecName] of newNameToECName)
      foldedNewNameToECName.set(foldName(newName), ecName);
  }
  return foldedNewNameToECName;
}

function getFoldedECNameToNewName(): ReadonlyMap<string, string> {
  if (foldedECNameToNewName === undefined) {
    foldedECNameToNewName = new Map();
    for (const [newName, ecName] of newNameToECName) {
      const foldedECName = foldECName(ecName);
      if (!foldedECNameToNewName.has(foldedECName))
        foldedECNameToNewName.set(foldedECName, newName);
    }
  }
  return foldedECNameToNewName;
}

function getFoldedNewNameToLegacyName(): ReadonlyMap<string, string> {
  if (foldedNewNameToLegacyName === undefined) {
    foldedNewNameToLegacyName = new Map();
    // When several legacy names map to one new name, use the first source registration for reverse lookup.
    for (const [legacyName, newName] of oldToNewName) {
      const foldedNewName = foldName(newName);
      if (!foldedNewNameToLegacyName.has(foldedNewName))
        foldedNewNameToLegacyName.set(foldedNewName, legacyName);
    }
  }
  return foldedNewNameToLegacyName;
}

/** Converts a legacy EC2 unit name to its EC 3.2 unit full name. */
export function ecUnitNameFromLegacyName(legacyName: string): string | undefined {
  const newName = getFoldedOldToNewName().get(foldName(legacyName));
  return newName === undefined ? undefined : getFoldedNewNameToECName().get(foldName(newName));
}

/** Converts an EC 3.2 unit full name to its legacy EC2 unit name. */
export function legacyUnitNameFromECName(ecName: string): string | undefined {
  const newName = getFoldedECNameToNewName().get(foldECName(ecName));
  return newName === undefined ? undefined : getFoldedNewNameToLegacyName().get(foldName(newName));
}
